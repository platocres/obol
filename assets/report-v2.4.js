// Obol v2.4 report overlay — operator queue / decision trail.
(function(root){
'use strict';
const old=root.OBOL_REPORT_V2||{},C=()=>root.OBOL_CORE_V2;
function esc(s){return String(s==null?'':s).replace(/\|/g,'\\|');}
function cardMap(lanes){const m={};for(const l of lanes||[])for(const c of l.cards||[])m[c.id]=c;return m;}
function queueSection(state,lanes){
  const cards=cardMap(lanes),rows=(state.workQueue||[]).slice().sort((a,b)=>String(a.updatedAt||a.createdAt).localeCompare(String(b.updatedAt||b.createdAt)));
  if(!rows.length)return'';
  const L=['## Operator Work Queue','', 'This section preserves the human planning trail separately from the automatically ranked Path. It records what the operator deliberately queued, completed, or deferred.',''];
  for(const x of rows){const c=cards[x.cardId],title=c?c.title:x.cardId;L.push('- **'+String(x.status||'planned').toUpperCase()+' · '+String(x.priority||'normal')+'** — '+esc(title)+' — '+esc(x.contextLabel||x.contextKey)+(x.note?' — '+esc(x.note):''));}
  L.push('');return L.join('\n');
}
function insertBeforeTail(md,section){if(!section)return md;const marker='\n---\n',i=md.lastIndexOf(marker);return i>=0?md.slice(0,i)+'\n\n'+section+'\n'+md.slice(i):md+'\n\n'+section;}
function generate(state,lanes,mode,opts){let md=old.generate?old.generate(state,lanes,mode,opts||{}):'';md=insertBeforeTail(md,queueSection(state,lanes));return md.replace(/Generated by Obol v2\.3/g,'Generated by Obol v2.4').replace(/\*\*Obol:\*\* v2\.3\.0/g,'**Obol:** v2.4.0');}
root.OBOL_REPORT_V2={...old,generate,_queueSection:queueSection};root.OBOL_REPORT_V24={version:'2.4.0'};
})(typeof window!=='undefined'?window:globalThis);