  // Everything the setup script TRIES to provide (non-Kali), with a where-to-get-it hint + its staged dest.
  // The probe uses this to report what best-effort install could not satisfy, so nothing fails silently.
  function installAttempts(A) {
    var m = {}, seen = {};
    Object.keys(A).forEach(function (k) {
      var e = A[k]; if (!e || seen[e.key]) return; seen[e.key] = 1;
      if (e.class === 'kali' || e.class === 'builtin') return;
      // Prefer a where-to-get-it URL; fall back to the install command so an apt/pipx failure still gives a next step.
      var hint = e.manual_url || e.url || (e.gh_repo ? 'https://github.com/' + e.gh_repo : '') || e.install || '';
      m[e.key] = { hint: hint, dest: e.dest || '' };
    });
    return m;
  }

  // The name->variants map the paste-back probe uses to detect which invocation a box exposes.
  function inventoryNames(A) {
    var names = {}, seen = {};
    Object.keys(A).forEach(function (k) {
      var e = A[k]; if (!e || e.class === 'builtin' || seen[e.key]) return; seen[e.key] = 1;
      names[e.key] = (e.variants && e.variants.length ? e.variants : [e.canonical || e.key]);
    });
    return names;
  }

  // -- paste-back: read the OBOL-ARSENAL block the script prints, into a machine profile --
  // The profile describes the OPERATOR'S BOX, not an engagement, so it lives per-browser (localStorage),
  // persisting across engagements. Reads are wrapped (a private window / blocked storage just means
  // "no profile yet"). parseInventory tolerates the whole terminal paste - it finds the marker + JSON.
  var PROFILE_KEY = 'obol.arsenal-profile';
  function parseInventory(text) {
    if (!text) return null;
    if (OBOL._decodeArsenalBlock) return OBOL._decodeArsenalBlock(text);
    text = String(text);
    var i = text.indexOf('OBOL-ARSENAL');
    var scan = i >= 0 ? text.slice(i) : text;         // allow a bare JSON paste too
    // find the first balanced {...} after the marker
    var start = scan.indexOf('{');
    if (start < 0) return null;
    var depth = 0, inStr = false, esc = false, end = -1;
    for (var p = start; p < scan.length; p++) {
      var c = scan[p];
      if (inStr) { if (esc) esc = false; else if (c === '\\') esc = true; else if (c === '"') inStr = false; continue; }
      if (c === '"') inStr = true;
      else if (c === '{') depth++;
      else if (c === '}') { depth--; if (depth === 0) { end = p + 1; break; } }
    }
    if (end < 0) return null;
    var obj;
    try { obj = JSON.parse(scan.slice(start, end)); } catch (e) { return null; }
    if (!obj || typeof obj !== 'object' || !obj.tools) return null;
    return obj;
  }
  function profileGet() { try { return JSON.parse(localStorage.getItem(PROFILE_KEY) || 'null'); } catch (e) { return null; } }
  function syncProfileToEngagement(inv) {
    if (!inv || typeof inv !== 'object') return;
    if (OBOL.store && typeof OBOL.store.update === 'function') {
      try {
        OBOL.store.update(function (eng) {
          if (!eng) return;
          eng.params = eng.params || {};
          if (inv.lhost && !eng.params.lhost) {
            eng.params.lhost = inv.lhost;
            eng.params.lhost_iface = inv.lhost_iface || 'tun0';
          }
          if (inv.tooldir && !eng.params.toolsDir) {
            eng.params.toolsDir = inv.tooldir;
          }
        }, 'arsenal-sync');
      } catch (e) {}
    }
    try { if (OBOL.ctxbar && typeof OBOL.ctxbar.render === 'function') OBOL.ctxbar.render(); } catch (e) {}
    try { if (OBOL.app && typeof OBOL.app.renderSidebar === 'function') OBOL.app.renderSidebar(); } catch (e) {}
  }
  function profileSet(inv) {
    if (!inv) return null;
    inv.savedAt = Date.now();
    try { localStorage.setItem(PROFILE_KEY, JSON.stringify(inv)); } catch (e) {}
    syncProfileToEngagement(inv);
    return inv;
  }
  function profileClear() { try { localStorage.removeItem(PROFILE_KEY); } catch (e) {} }
  // Ingest a raw paste -> store it as the profile. Returns {ok, present, staged, wordlists, lhost, lhost_iface, reason}.
  function ingestInventory(text) {
    var inv = parseInventory(text);
    if (!inv) return { ok: false, reason: 'no OBOL-ARSENAL block found in that paste' };
    profileSet(inv);
    var present = 0; Object.keys(inv.tools || {}).forEach(function (k) { if (inv.tools[k] && inv.tools[k].present) present++; });
    return {
      ok: true,
      present: present,
      staged: (inv.staged || []).length,
      wordlists: Object.keys(inv.wordlists || {}).length,
      lhost: inv.lhost || '',
      lhost_iface: inv.lhost_iface || ''
    };
  }

  OBOL.arsenal = {
    buildScript: buildScript, inventoryNames: inventoryNames,
    parseInventory: parseInventory, ingestInventory: ingestInventory,
    profileGet: profileGet, profileSet: profileSet, profileClear: profileClear,
  };
