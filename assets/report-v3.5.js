// Obol v3.5 report overlay — current release labels and explicit external-proof wording.
(function(root){
'use strict';
const R=root.OBOL_REPORT_V2;if(!R||!R.generate)return;const oldGenerate=R.generate;
function version35(state){return 'v'+String(state&&state.obolVersion||root.OBOL_CORE_V2&&root.OBOL_CORE_V2.VERSION||'3.5.0').replace(/\.0$/,'');}
function generate35(state,lanes,mode,opts){
  let md=oldGenerate(state,lanes,mode,opts||{}),v=version35(state);
  md=md.replace(/Generated by Obol v\d+(?:\.\d+)*/g,'Generated by Obol '+v);
  md=md.replace(/screenshot the required proof/gi,'record the required proof screenshot externally');
  md=md.replace(/Add required screenshots/gi,'Add required externally captured proof screenshots');
  return md;
}
R.generate=generate35;root.OBOL_REPORT_V35={version:'3.5.0',generate:generate35};
})(typeof window!=='undefined'?window:globalThis);
