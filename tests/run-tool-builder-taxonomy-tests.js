'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const root=path.join(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const source=read('data/product-hardening/tool-builder-backlog-current.js');
assert(!source.includes('Remaining Tool Builder inventory by function'),'current owner must not expose backlog mechanics as a Tools category');
assert(source.includes('Web discovery and HTTP'),'approved taxonomy should include web/HTTP');
assert(source.includes('Active Directory, Kerberos, LDAP, and PKI'),'approved taxonomy should include AD/Kerberos/LDAP/PKI');
assert(source.includes('SMB, RPC, and network services'),'approved taxonomy should include SMB/RPC/services');
assert(source.includes('Databases'),'approved taxonomy should split databases out of cloud/containers');
const sandbox={window:{},globalThis:null,location:{hash:'#/tools'},addEventListener(){},setTimeout(){},localStorage:{getItem(){return null;},setItem(){}}};
sandbox.globalThis=sandbox.window=sandbox;
vm.createContext(sandbox);
vm.runInContext(read('data/tool-builder-inventory.js'),sandbox,{filename:'data/tool-builder-inventory.js'});
vm.runInContext(source,sandbox,{filename:'data/product-hardening/tool-builder-backlog-current.js'});
const api=sandbox.OBOL_TOOL_BUILDER_IMPLEMENTATION_AUDIT_CURRENT;
assert(api,'Tool Builder API should load');
const allowed=new Set(api.operatorTaxonomy.map(g=>g.id));
assert(allowed.size>=10,'taxonomy should expose real operator categories');
const records=sandbox.OBOL_TOOL_BUILDER_INVENTORY.all();
const seen=new Map();
for(const record of records){
 const group=api.groupForTool(record.tool);
 assert(allowed.has(group.id),'unexpected category id '+group.id+' for '+record.tool);
 assert(!/remaining|inventory complete|backlog/i.test(group.title),'category should not be backlog mechanics: '+group.title);
 const key=sandbox.OBOL_TOOL_BUILDER_INVENTORY.key(record.tool);
 assert(!seen.has(key),'inventory tool should not appear as duplicate canonical key: '+key);
 seen.set(key,group.id);
}
assert.strictEqual(api.groupForTool('enum4linux').id,'smb-rpc-services','classic enum4linux belongs with SMB/RPC/service enumeration');
assert.strictEqual(api.groupForTool('certipy').id,'ad-kerberos-pki','Certipy belongs with AD/Kerberos/LDAP/PKI');
assert.strictEqual(api.groupForTool('mimikatz').id,'credentials','Mimikatz belongs with credentials/secrets, not generic privesc');
assert.strictEqual(api.groupForTool('proxychains').id,'pivoting','proxychains belongs with pivoting/proxying/tunneling');
assert.strictEqual(api.groupForTool('tftp').id,'shells-transfer','tftp belongs with transfer helpers');
assert.strictEqual(api.groupForTool('sshpass').id,'remote-access-exec','sshpass belongs with remote access');
assert(records.some(r=>r.status==='modeled'),'test fixture should include modeled records');
assert(records.some(r=>r.status==='implemented'),'test fixture should include implemented records');
console.log('Tool Builder operator taxonomy regression passed.');
