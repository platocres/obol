'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const root=path.join(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const doc=read('docs/TOOL-BUILDER-IMPLEMENTATION-STANDARD.md');
assert(doc.includes('Reuse plumbing. Preserve tool identity.'),'standard should state the core rule');
assert(doc.includes('Bespoke profile required for every implemented tool'),'standard should require per-tool bespoke profiles');
assert(doc.includes('ffuf'),'standard should call out neighboring tools that must not smear together');
assert(doc.includes('impacket-secretsdump'),'standard should distinguish Impacket tools by purpose');
assert(doc.includes('no live Tools route category is named after backlog state'),'standard should ban backlog-state categories in the live Tools route');
const taxonomy=read('docs/TOOL-BUILDER-INVENTORY-ORGANIZATION.md');
assert(taxonomy.includes('The Tools route uses one operator taxonomy'),'taxonomy doc should forbid a second live taxonomy');
assert(taxonomy.includes('Databases'),'taxonomy doc should split databases from cloud/containers');
const sandbox={window:{},globalThis:null,location:{hash:'#/tools'},addEventListener(){},setTimeout(){},localStorage:{getItem(){return null;},setItem(){}}};
sandbox.globalThis=sandbox.window=sandbox;
vm.createContext(sandbox);
vm.runInContext(read('data/tool-builder-inventory.js'),sandbox,{filename:'data/tool-builder-inventory.js'});
vm.runInContext(read('data/product-hardening/tool-builder-backlog-current.js'),sandbox,{filename:'data/product-hardening/tool-builder-backlog-current.js'});
const api=sandbox.OBOL_TOOL_BUILDER_IMPLEMENTATION_AUDIT_CURRENT;
assert(api,'Tool Builder audit API should load');
assert.strictEqual(api.implementationStandard.rule,'reuse plumbing, preserve tool identity');
assert(api.implementationStandard.sharedPrimitiveKinds.length>=8,'standard should expose reusable primitive kinds');
assert(api.implementationStandard.requiredProfileFields.includes('whyChooseThisTool'),'standard should require why-this-tool identity');
assert(api.implementationStandard.requiredProfileFields.includes('nearestNeighbors'),'standard should require neighbor distinction');
assert(api.implementationStandard.requiredProfileFields.includes('factsItCannotProve'),'standard should require proof boundaries');
assert(api.implementationStandard.forbidden.some(x=>/generic factory category/.test(x)),'standard should forbid generic operator-facing factory categories');
assert(api.operatorTaxonomy.length>=10,'operator taxonomy should be exposed for tests/planning');
assert.strictEqual(api.groupForTool('enum4linux').id,'smb-rpc-services');
assert.strictEqual(api.groupForTool('certipy').id,'ad-kerberos-pki');
assert.strictEqual(api.groupForTool('mimikatz').id,'credentials');
console.log('Tool Builder implementation standard regression passed.');
