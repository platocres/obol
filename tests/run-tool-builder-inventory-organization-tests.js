'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const vm=require('vm');
const root=path.join(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const sandbox={window:{},globalThis:null,location:{hash:'#/tools'},addEventListener(){},setTimeout(){},localStorage:{getItem(){return null;},setItem(){}}};
sandbox.globalThis=sandbox.window=sandbox;
vm.createContext(sandbox);
for(const rel of ['data/tool-builder-inventory.js','data/product-hardening/tool-builder-backlog-current.js']){
 vm.runInContext(read(rel),sandbox,{filename:rel});
}
const api=sandbox.OBOL_TOOL_BUILDER_IMPLEMENTATION_AUDIT_CURRENT;
assert(api,'Tool Builder backlog current owner should expose the audit API');
assert(/^v10\.(?:20|21|[2-9]\d)$/.test(api.version),'inventory organization owner should advertise the current v10 grouping line');
const groups=Array.from(api.modeledInventoryGroups());
const byId=Object.fromEntries(groups.map(group=>[group.id,Array.from(group.tools)]));
assert(byId['ad-kerberos-pki']&&byId['ad-kerberos-pki'].includes('bloodhound-cypher'),'AD/Kerberos/LDAP/PKI slice should capture BloodHound/AD tooling');
assert(byId['remote-access-exec']&&byId['remote-access-exec'].includes('impacket-mssqlclient'),'remote access/execution slice should capture MSSQL/lateral tooling');
assert(byId.pivoting&&byId.pivoting.includes('ptunnel-ng'),'pivoting slice should capture tunnel transports');
assert(byId['smb-rpc-services']&&byId['smb-rpc-services'].includes('smbclient-ng'),'SMB/RPC/services slice should capture service enumeration tools');
assert(byId.credentials&&byId.credentials.includes('mitm6'),'credential slice should capture relay/capture tooling');
assert(byId.privesc&&byId.privesc.includes('godpotato'),'privilege escalation slice should capture PE helpers');
assert(byId.web&&byId.web.includes('nuclei'),'web/request slice should capture scanner/request tools');
assert(byId['cloud-containers']&&byId['cloud-containers'].includes('kubectl'),'cloud/container slice should capture container/cloud tooling');
assert(byId.databases&&byId.databases.includes('redis-cli'),'database slice should capture database tooling');
assert(byId['exploit-cve']&&byId['exploit-cve'].includes('cve-2024-29849'),'exploit/CVE slice should capture named CVE wrappers');
const batch=api.activeBatches()[0];
assert(batch.groups&&batch.groups.length>=8,'active batch should expose grouped remaining inventory, not only one flat tools array');
assert.strictEqual(api.groupForTool('enum4linux').title,'SMB, RPC, and network services','classic tools should be classified by operator function, not dismissed as trash');
assert.strictEqual(api.groupForTool('certipy').title,'Active Directory, Kerberos, LDAP, and PKI','Certipy should live in AD/Kerberos/LDAP/PKI');
assert.strictEqual(api.groupForTool('mimikatz').title,'Credentials, cracking, and secrets','Mimikatz should live in credential/secret handling');
const source=read('data/product-hardening/tool-builder-backlog-current.js');
assert(!source.includes('Remaining Tool Builder inventory by function'),'live Tools regrouping must not create a backlog-named operator category');
assert(source.includes('reuse plumbing, preserve tool identity'),'current owner should expose the bespoke/reuse implementation standard');
console.log('Tool Builder inventory organization regression passed.');
