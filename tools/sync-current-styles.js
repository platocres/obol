'use strict';

const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const crypto=require('crypto');
const manifest=require(path.join(root,'data','runtime-manifest.js'));
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8').replace(/\r\n/g,'\n');
const fingerprint=list=>crypto.createHash('sha256').update(list.join('\n')).digest('hex');
const target=path.join(root,'assets','obol-current.css');

function historicalStyles(){
 const list=manifest.compatibility&&manifest.compatibility.historicalStyles;
 if(!Array.isArray(list)||!list.length)throw new Error('runtime manifest compatibility.historicalStyles is required');
 return list;
}
function expected(){
 const fragments=historicalStyles();
 for(const rel of fragments){
  if(!/^assets\/[^/]+\.css$/.test(rel))throw new Error('Historical stylesheet must stay inside assets/: '+rel);
  if(rel===path.relative(root,target).split(path.sep).join('/'))throw new Error('current stylesheet owner cannot import itself');
 }
 const head=[
  '/*',
  ' * Generated by tools/sync-current-styles.js from data/runtime-manifest.js.',
  ' * Do not edit manually.',
  ' *',
  ' * This file is the single current stylesheet owner. It is the exact ordered',
  ' * concatenation of the '+fragments.length+' historical fragments, so the cascade is',
  ' * byte-for-byte what the historical import chain produced while costing one',
  ' * request instead of '+(fragments.length+1)+'. The fragments remain on disk as the',
  ' * frozen regression ledger.',
  ' *',
  ' * Fragment order sha256: '+fingerprint(fragments),
  ' */',
  ''
 ].join('\n');
 return head+fragments.map(rel=>'/* obol-style-fragment: '+rel+' */\n'+read(rel).replace(/\s+$/,'')+'\n').join('');
}

const next=expected();
const current=fs.existsSync(target)?fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n'):'';
if(process.argv.includes('--write')){
 fs.writeFileSync(target,next);
 console.log('Current stylesheet owner synchronized from runtime manifest.');
}else if(current!==next){
 console.error('assets/obol-current.css is out of sync. Run node tools/sync-current-styles.js --write');
 process.exit(1);
}else{
 console.log('Current stylesheet owner matches runtime manifest.');
}

module.exports={historicalStyles,expected};
