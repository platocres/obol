'use strict';

const fs=require('fs');
const path=require('path');
const vm=require('vm');

const root=path.join(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const fail=[];
function bad(message){fail.push(message);}

const sandbox={window:{},globalThis:null};
sandbox.globalThis=sandbox.window;
vm.createContext(sandbox);
vm.runInContext(read('data/current-release.js'),sandbox,{filename:'data/current-release.js'});
const release=sandbox.window.OBOL_CURRENT_RELEASE;
const identity=sandbox.window.OBOL_RELEASE_IDENTITY;

if(!release)bad('current release authority is unavailable');
if(!identity)bad('release identity helper is unavailable');
if(identity&&identity.release!==release)bad('release identity helper does not share the current release authority');
if(identity&&typeof identity.normalizeReportMarkdown!=='function')bad('release identity helper does not normalize report markdown');
if(identity&&typeof identity.stampState!=='function')bad('release identity helper does not stamp exported/workspace release metadata');

if(release&&identity){
  const evidencePayload='**Obol:** v2.0\n\n\nGenerated by Obol v2.0 inside operator evidence';
  const stale=[
    '# Penetration Test Report — Draft',
    '',
    '**Generated:** 2026-08-31  ',
    '**Obol:** v8.8  ',
    '**Workspace schema:** 8.8.0',
    '',
    '```text',
    evidencePayload,
    '```',
    '',
    '---',
    '_Generated by Obol v8.8 from operator-recorded ledger state. Review every statement before delivery._'
  ].join('\n');
  const normalized=identity.normalizeReportMarkdown(stale);
  const normalizedTwice=identity.normalizeReportMarkdown(normalized);
  const escapedLabel=release.label.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
  if((normalized.match(new RegExp('^\\*\\*Obol release:\\*\\* '+escapedLabel+'\\s*$','gm'))||[]).length!==1)bad('normalized report must contain exactly one current Obol release metadata line');
  if(/^\*\*Obol:\*\*\s*v8\.8\s*$/m.test(normalized))bad('normalized report retains the stale report-owned Obol v8.8 metadata line');
  if(!normalized.includes('_Generated by Obol '+release.label+' from operator-recorded ledger state.'))bad('normalized report footer does not use the current release label');
  if(!normalized.includes('**Workspace schema:** 8.8.0'))bad('report normalization must preserve the workspace schema identity');
  if(!normalized.includes(evidencePayload))bad('report normalization must preserve operator evidence text and whitespace verbatim');
  if(normalizedTwice!==normalized)bad('report version normalization is not idempotent');

  const exportState={schemaVersion:'8.8.0',obolRelease:'9.2.0',obolReleaseLabel:'v9.2'};
  identity.stampState(exportState);
  if(exportState.obolRelease!==release.version||exportState.obolReleaseLabel!==release.label)bad('sanitized/export metadata does not stamp the current product release');
  if(exportState.schemaVersion!=='8.8.0')bad('product release stamping must not rewrite the workspace schema version');
}

const app=read('assets/app-v8.8.js');
const readme=read('README.md');
const dashboard=read('assets/product-hardening-dashboard.js');
const standalone=read('product-hardening.html');
const core=read('assets/core-v8.8.js');
const reportBase=read('assets/report-v2.js');
const reportCurrentOverlay=read('assets/report-v3.5.js');

if(release&&!readme.includes('Current release: **'+release.label+'**'))bad('README current release does not agree with the authority');
for(const token of [
  'window.OBOL_RELEASE_IDENTITY',
  'i.normalizeReportMarkdown(md)',
  'i.stampState(state)',
  'i.stampState(safe)',
  "tag.textContent='Offensive Box Operations Ledger · '+r.label",
  "const title='Obol '+r.label+' — '+r.phaseLabel",
  "Current Obol release: <b>'+e88(r.label)+'"
])if(!app.includes(token))bad('live app version-trust integration missing token: '+token);
if(!app.includes('window.OBOL_REPORT_V2={...R,generate}'))bad('final report generator is not wrapped by current release normalization');
if(!dashboard.includes('window.OBOL_CURRENT_RELEASE'))bad('Product Hardening Dashboard does not consume current release authority');
if(!standalone.includes('data/current-release.js'))bad('standalone dashboard does not load current release authority');
if(!core.includes('C.VERSION=VERSION'))bad('workspace/runtime schema ownership changed unexpectedly');
if(!reportBase.includes('state.obolVersion')||!reportBase.includes('C().VERSION'))bad('historical base report no longer exposes the workspace-derived identity fixture expected by current normalization');
if(!reportCurrentOverlay.includes('function version35(state)'))bad('historical report overlay fixture changed unexpectedly');

if(fail.length){
  console.error('Version identity validation failed:');
  for(const item of fail)console.error('- '+item);
  process.exit(1);
}
console.log('Version identity valid:',release.label,'across visible UI, report metadata/footer normalization, and exported product metadata; workspace schema remains v8.8.');
