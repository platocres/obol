'use strict';

/*
 * Generates assets/obol-core-current.js as the current owner for the core state
 * and derivation area.
 *
 * The core chain is closure-heavy: release overlays intentionally capture older
 * migration, ranking, report, and project-model functions before replacing the
 * current C.* entrypoints. A graph-only serializer would lose those closures.
 * This generator therefore preserves each historical release delta as an
 * isolated lexical block inside one current owner. The browser and Node runtime
 * execute the stable owner directly; the 69 versioned core files remain as the
 * frozen equivalence ledger and are no longer the current execution path.
 */

const crypto=require('crypto');
const fs=require('fs');
const path=require('path');
const vm=require('vm');

const root=path.join(__dirname,'..');
const manifest=require(path.join(root,'data','runtime-manifest.js'));
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8').replace(/\r\n/g,'\n');
const sha=value=>crypto.createHash('sha256').update(value).digest('hex');
const baseGlobalExports=[
 'addArtifact','addCredential','addFact','applicable','applyEvidenceUpdate',
 'cardPhaseWeight','clean','coerceState','commandId','contextKey','contextLabel',
 'detectSecretType','domainForContext','effectiveFactRecords','effectiveFacts',
 'ensureDomain','ensureIdentity','factReasons','factScope','factVisibleInContext',
 'grounded','hasFact','hostForContext','labelFact','latestActivity','mergeHost',
 'migrateV1','newState','normalizeArtifact','normalizeContext','normalizeDomain',
 'normalizeHost','now','optionId','phaseLevel','rankCard','rankedApplicable',
 'recordActivity','removeFact','resetCard','sanitizedCopy','simpleHash','slug',
 'snapshotApplicable','statusFor','uid','whyNow'
];

function coreArea(){
 const area=(manifest.bundles&&manifest.bundles.areas||[]).find(candidate=>candidate.id==='core');
 if(!area)throw new Error('runtime manifest does not declare the core ownership area');
 if(area.strategy!=='semantic-delta-replay')throw new Error('core area must use the semantic-delta-replay strategy');
 if(!manifest.coreCurrent||manifest.coreCurrent.owner!==area.owner)throw new Error('manifest.coreCurrent must point at the core owner');
 return area;
}

function overlayBlock(rel){
 const body=read(rel).replace(/\s+$/,'');
 const match=body.match(/^((?:\/\/[^\n]*\n|\/\*[\s\S]*?\*\/\s*)*)\(function\(root\)\{\n?([\s\S]*?)\n?\}\)\(typeof window!=='undefined'\?window:globalThis\);\s*$/);
 if(!match)throw new Error('core overlay does not match the expected classic IIFE shape: '+rel);
 const comment=match[1].trim();
 const delta=match[2].replace(/^\s*'use strict';\s*/,'');
 return [
  '/* obol-core-delta: '+rel+' */',
  '{',
  comment,
  delta,
  '}',
  ''
 ].filter((line,index)=>line!==''||index>1).join('\n');
}

function baseScopeBlock(fragments){
 return [
  '/* obol-core-base-scope: '+fragments.join(' + ')+' */',
  '{',
  fragments.map(rel=>read(rel).replace(/\s+$/,'')).join('\n'),
  'Object.assign(root,{'+baseGlobalExports.map(name=>name+':'+name).join(',')+'});',
  '}',
  ''
 ].join('\n');
}

function emitBody(area){
 const fragments=area.fragments;
 if(fragments[0]!=='assets/core-v2-base.js'||fragments[1]!=='assets/core-v2.js')throw new Error('core base scope must begin with core-v2-base.js plus core-v2.js');
 return [
  '(function(root){',
  '\'use strict\';',
  baseScopeBlock(fragments.slice(0,2)),
  fragments.slice(2).map(overlayBlock).join('\n'),
  '})(typeof window!==\'undefined\'?window:globalThis);',
  ''
 ].join('\n');
}

function expected(){
 const area=coreArea();
 const body=emitBody(area);
 new vm.Script(body,{filename:area.owner});
 return [
  '/*',
  ' * Generated by tools/sync-core-current.js from data/runtime-manifest.js.',
  ' * Do not edit manually.',
  ' *',
  ' * Ownership area: core (startup) - Core state and derivation.',
  ' * '+area.description,
  ' *',
  ' * This file is the single current runtime owner for '+area.fragments.length+' historical',
  ' * core fragments. It replays their surviving release deltas as isolated lexical',
  ' * blocks rather than as exact historical-file concatenation, preserving the',
  ' * migration and ranking closures while removing the versioned fragment chain',
  ' * from current browser and Node execution.',
  ' *',
  ' * Historical fragment order sha256: '+sha(area.fragments.join('\n')),
  ' * Generated body sha256: '+sha(body),
  ' * First fragment: '+area.fragments[0],
  ' * Last fragment:  '+area.fragments[area.fragments.length-1],
  ' */',
  '',
  body
 ].join('\n');
}

function main(){
 const area=coreArea();
 const target=path.join(root,area.owner);
 const next=expected();
 const current=fs.existsSync(target)?fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n'):'';
 if(process.argv.includes('--write')){
  if(current!==next)fs.writeFileSync(target,next);
  console.log('Core current owner synchronized: '+area.owner+' replays '+area.fragments.length+' historical core deltas.');
 }else{
  if(current!==next){
   console.error(area.owner+' is out of sync with the generated current core owner.');
   console.error('Run node tools/sync-core-current.js --write');
   process.exit(1);
  }
  console.log('Core current owner matches the generated semantic delta replay for '+area.fragments.length+' historical fragments.');
 }
}

if(require.main===module)main();

module.exports={coreArea,overlayBlock,baseScopeBlock,emitBody,expected,baseGlobalExports,main};
