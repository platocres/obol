'use strict';

const fs=require('fs');
const path=require('path');
const {loadCurrent}=require('./current-runtime');

const root=path.join(__dirname,'..');
const {C,lanes}=loadCurrent(root);
if(!C||!C.projectModel66)throw new Error('Current project model unavailable');

const START='<!-- OBOL-BUILD-NEXT:START -->';
const END='<!-- OBOL-BUILD-NEXT:END -->';

function clean(s){return String(s||'').replace(/\s+/g,' ').trim();}
function rowLine(r,i){
  const missing=(r.missing||[]).length?' Missing contracts: '+r.missing.join(', ')+'.':'';
  return `${i+1}. **${clean(r.label)}** — ${clean(r.file||'project-wide')} · ${clean(r.kind).replace(/-/g,' ')}.${missing}`;
}
function render(){
  const p=C.projectModel66(C.newState(),lanes),q=p.buildNext,c=p.canonical,s=p.source,top=(q.rows||[]).slice(0,6);
  return [
    START,
    'This block is generated from the same current project model used by the North Star Dashboard. Do not edit it manually.',
    '',
    `**Current live queue:** ${q.total} items — ${p.quality.implementedQuality} implemented-quality repairs, ${p.quality.mappedDelivery} mapped-delivery repairs, ${p.quality.canonicalGaps} canonical gaps.`,
    `**Canonical methodology:** ${c.implemented}/${c.total} fully implemented (${c.completePct}%), ${c.partial} partial, ${c.gap} gaps, ${c.representedPct}% represented.`,
    `**Source fidelity:** ${s.filesAtomized}/${s.filesTotal} source files atomized, ${s.baselinesAtomized}/${s.baselinesTotal} partial baselines decomposed, ${s.atomicComplete}/${s.atomicTotal} inventoried atomic units fidelity-complete.`,
    `**Current phase:** ${clean(p.phase.title)}.`,
    '',
    '**Highest-priority live items:**',
    ...(top.length?top.map(rowLine):['No queued items.']),
    '',
    'Generated by `node tools/sync-readme-build-next.js --write`. Verify with `node tools/sync-readme-build-next.js --check`.',
    END
  ].join('\n');
}
function replaceBlock(readme,block){
  const a=readme.indexOf(START),b=readme.indexOf(END);
  if(a<0||b<a)throw new Error('README Build Next markers are missing or malformed');
  return readme.slice(0,a)+block+readme.slice(b+END.length);
}

const readmePath=path.join(root,'README.md'),mode=process.argv[2]||'--check',block=render();
if(mode==='--print'){process.stdout.write(block+'\n');process.exit(0);}
const current=fs.readFileSync(readmePath,'utf8'),next=replaceBlock(current,block);
if(mode==='--write'){
  if(next!==current)fs.writeFileSync(readmePath,next);
  console.log(next===current?'README Build Next snapshot already synchronized.':'README Build Next snapshot synchronized.');
  process.exit(0);
}
if(mode==='--check'){
  if(next!==current){
    console.error('README Build Next snapshot is out of sync with the current project model.');
    console.error('Run: node tools/sync-readme-build-next.js --write');
    console.error('\nExpected generated block:\n'+block);
    process.exit(1);
  }
  console.log('README Build Next snapshot matches the current project model.');
  process.exit(0);
}
throw new Error('Usage: node tools/sync-readme-build-next.js --check|--write|--print');
