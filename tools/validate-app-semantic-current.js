'use strict';

const assert=require('assert');
const fs=require('fs');
const path=require('path');
const vm=require('vm');

const root=path.join(__dirname,'..');
const manifest=require(path.join(root,'data','runtime-manifest.js'));
const appCurrent=require('./sync-app-current');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8').replace(/\r\n/g,'\n');

function main(){
 const area=(manifest.bundles&&manifest.bundles.areas||[]).find(candidate=>candidate.id==='app');
 assert(area,'runtime manifest declares the application ownership area');
 assert.strictEqual(area.scope,'startup','application semantics remain part of operator startup');
 assert.strictEqual(area.owner,'assets/obol-app-current.js','application owner stays stable and non-versioned');
 assert.strictEqual(area.strategy,'semantic-delta-replay','application ownership is semantic rather than exact concatenation');
 assert.strictEqual(area.fragments.length,43,'the v9.43 surviving 43-fragment semantic ledger remains intact');

 const app=manifest.appCurrent;
 assert(app,'runtime manifest declares appCurrent metadata');
 assert.strictEqual(app.owner,area.owner,'appCurrent points at the stable application owner');
 assert.strictEqual(app.strategy,'semantic-delta-replay','appCurrent records semantic execution ownership');
 assert.strictEqual(app.sourceRelease,'v9.47','v9.47 owns semantic application retirement');
 assert.strictEqual(app.requestRetirementRelease,'v9.43','v9.43 remains recorded as request/stale-overlay retirement');
 assert.strictEqual(app.firstPaintRelease,'v9.46','v9.46 remains recorded as the first-paint barrier milestone');
 assert.strictEqual(app.generator,'tools/sync-app-current.js','appCurrent names the semantic generator');
 assert.strictEqual(app.semanticValidator,'tools/validate-app-semantic-current.js','appCurrent names this semantic ownership proof');
 assert.strictEqual(app.equivalenceValidator,'tools/validate-app-current-equivalence.js','the historical retirement proof remains attached');
 assert.strictEqual(app.domEquivalenceValidator,'tools/validate-app-dom-equivalence.js','the browser DOM equivalence proof remains attached');
 assert.deepStrictEqual(Array.from(app.historicalFragments),Array.from(area.fragments),'appCurrent records all surviving semantic source fragments');

 const disk=read(area.owner),expected=appCurrent.expected();
 assert.strictEqual(disk,expected,area.owner+' is out of sync — run node tools/sync-app-current.js --write');
 assert(!disk.includes('obol-runtime-fragment:'),'semantic application owner is not an exact-concatenation bundle');
 assert(disk.includes('Generated by tools/sync-app-current.js'),'semantic application owner declares its generator');
 assert(disk.includes("root.__OBOL_HISTORICAL_APP_SCHEDULERS_DISABLED__=true"),'semantic owner records historical scheduler retirement');
 assert(disk.includes("root.OBOL_CURRENT_APPLICATION=Object.freeze"),'semantic owner exposes one stable application/router API');
 assert(disk.includes("__nativeAdd('hashchange',currentRoute)"),'semantic owner installs one current navigation listener after replay');
 assert(disk.includes('__runHistoricalTransaction'),'semantic owner runs surviving rendering deltas only inside a current route transaction');
 assert(disk.includes('queue.sort((a,b)=>a.delay-b.delay||a.sequence-b.sequence)'),'historical decorator delays are collapsed deterministically before current commit');
 assert(!disk.includes("ensureRelease88().catch(()=>{});ensureWorkflow88().catch(()=>{})"),'the historical v8.8 bridge no longer bootstraps current release/workflow ownership');
 for(const rel of appCurrent.CURRENT_MODULES)assert(disk.includes('obol-current-module: '+rel),'semantic owner embeds stable current module '+rel);
 for(const rel of area.fragments)assert(disk.includes('obol-app-delta: '+rel),'semantic owner traces the surviving source ledger: '+rel);
 const markers=(disk.match(/obol-app-delta:/g)||[]).length;
 assert.strictEqual(markers,area.fragments.length,'semantic owner has exactly one trace marker for each surviving historical fragment');
 for(const forbidden of ['vm.runInContext','vm.runInThisContext','fs.readFile','document.write(manifest'])assert(!disk.includes(forbidden),'current browser owner must not dynamically execute historical files: '+forbidden);
 new vm.Script(disk,{filename:area.owner});

 assert(manifest.startupBundleScripts.includes(area.owner),'browser startup loads the current application owner');
 for(const rel of area.fragments)assert(!manifest.startupBundleScripts.includes(rel),'browser startup never loads historical application fragment directly: '+rel);
 for(const rel of app.retiredFragments){
  assert(fs.existsSync(path.join(root,rel)),'retired application overlay remains on disk as frozen regression history: '+rel);
  assert(!area.fragments.includes(rel),'v9.43 retired overlay does not re-enter the semantic source ledger: '+rel);
 }

 console.log('Application semantic owner valid: '+area.fragments.length+' fragments still contribute behavior as frozen semantic deltas, '+app.retiredFragments.length+' stale overlays remain provably inert against live C.VERSION '+app.retirementGateValue+', and autonomous historical route schedulers/listeners no longer own browser execution.');
}

if(require.main===module)main();
module.exports={main};
