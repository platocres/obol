'use strict';
const fs=require('fs');
const path=require('path');
const target=path.join(__dirname,'apply-v9.35-build.js');
let src=fs.readFileSync(target,'utf8');
src=src.split('\\\\`').join('\\`');
const startMarker="write('docs/v9.35.md',`";
const start=src.indexOf(startMarker);
if(start<0)throw new Error('v9.35 docs template start not found');
const bodyStart=start+startMarker.length;
const end=src.indexOf("\n`);",bodyStart);
if(end<0)throw new Error('v9.35 docs template end not found');
const body=src.slice(bodyStart,end).replace(/(?<!\\)`/g,'\\`');
src=src.slice(0,bodyStart)+body+src.slice(end);
fs.writeFileSync(target,src);
console.log('Temporary v9.35 transformer quoting repaired.');
